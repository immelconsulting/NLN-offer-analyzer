import { describe, it, expect } from "vitest";
import { buildScriptPdf, scriptPdfFilename } from "../src/lib/scriptPdf.js";

const flatten = (node) =>
  typeof node === "string"
    ? node
    : Array.isArray(node)
      ? node.map(flatten).join("")
      : node && typeof node === "object"
        ? ["text", "stack", "ul", "ol", "table", "body", "content"].map((k) => (k in node ? flatten(node[k]) : "")).join("")
        : "";

const script = `# Your Counter-Offer Script

Hi Pat.

| Component | Offer |
|---|---|
| Base | $145,000 |

🗣️ "Thank you so much for the offer." ✅

- Pause.`;

describe("script PDF", () => {
  const doc = buildScriptPdf({ script, title: "Fallback Title", subtitle: "PM at Acme · Denver, CO" });
  const text = flatten(doc.content);

  it("uses the script's own heading as the title, once", () => {
    expect(text.match(/Your Counter-Offer Script/g)).toHaveLength(1);
    expect(text).not.toContain("Fallback Title");
  });

  it("turns the speech marker into 'Say:' and drops other emoji", () => {
    expect(text).toContain('Say: "Thank you so much for the offer."');
    expect(text).not.toMatch(/\p{Extended_Pictographic}/u);
  });

  it("keeps the comp table and the AI disclaimer (compliance copy)", () => {
    expect(doc.content.some((n) => n.table)).toBe(true);
    expect(text).toMatch(/generated by AI based on NLN's methodology/);
  });

  it("makes a safe filename", () => {
    expect(scriptPdfFilename("Your Counter-Offer Script")).toBe("Your-Counter-Offer-Script.pdf");
  });
});
