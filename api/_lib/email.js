import { Marked } from "marked";
import { CONTACT_EMAIL } from "../../src/lib/config.js";

// Outbound email through Resend (domain nextlevelnegotiation.com, verified
// via Wix DNS). Used for the JobJenny session alert and for emailing buyers
// their script. Throws on failure; callers decide whether that matters.

export async function sendEmail({ from, to, cc, replyTo, subject, text, html }) {
  const apiKey = process.env.RESEND_API_KEY;
  if (!apiKey) throw new Error("RESEND_API_KEY is not set");

  const r = await fetch("https://api.resend.com/emails", {
    method: "POST",
    headers: { Authorization: `Bearer ${apiKey}`, "Content-Type": "application/json" },
    body: JSON.stringify({ from, to, cc, reply_to: replyTo, subject, text, html }),
  });
  if (!r.ok) throw new Error(`Resend ${r.status}: ${await r.text()}`);
}

const escapeHtml = (s) =>
  s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");

// The script is model output, so any raw HTML in it is shown as text rather
// than rendered into the email.
const scriptMarked = new Marked({ renderer: { html: ({ text }) => escapeHtml(text) } });

// Email clients ignore most stylesheets, so the few styles that matter go
// inline on the tags the scripts actually use.
const INLINE_STYLES = {
  h1: "font-size:22px;color:#001E34;margin:24px 0 8px",
  h2: "font-size:18px;color:#001E34;margin:24px 0 8px;border-bottom:1px solid #E2E8F0;padding-bottom:4px",
  h3: "font-size:16px;color:#001E34;margin:18px 0 6px",
  p: "margin:0 0 12px",
  table: "border-collapse:collapse;width:100%;margin:0 0 14px;font-size:14px",
  th: "border:1px solid #CBD5E1;background:#D8F0F8;padding:6px 8px;text-align:left",
  td: "border:1px solid #CBD5E1;padding:6px 8px",
  blockquote: "border-left:4px solid #6BCCF7;margin:0 0 12px;padding:2px 12px;font-style:italic;color:#475569",
  a: "color:#0099CC",
};

function styleTags(html) {
  return html.replace(/<(h1|h2|h3|p|table|th|td|blockquote|a)(\s|>)/g, (m, tag, after) =>
    `<${tag} style="${INLINE_STYLES[tag]}"${after}`
  );
}

const DISCLAIMER =
  "This script was generated by AI based on NLN's methodology and the details you provided. " +
  "It's meant as general guidance, not personalized legal, financial, or professional advice, " +
  "and outcomes aren't guaranteed.";

export async function sendScriptEmail({ to, title, script, scriptUrl }) {
  // Titles read "Your Counter-Offer Script"; mid-sentence that's "your ...".
  const inSentence = title.replace(/^Your\b/, "your");
  const body = styleTags(scriptMarked.parse(script));
  const html = `<div style="font-family:Arial,Helvetica,sans-serif;font-size:15px;line-height:1.5;color:#334155;max-width:640px">
<p style="margin:0 0 12px">Here's a copy of ${escapeHtml(inSentence)}, so you always have it.</p>
<p style="margin:0 0 20px">You can also reopen it any time, on any device, and download it as a PDF:<br>
<a href="${scriptUrl}" style="color:#0099CC">${escapeHtml(scriptUrl)}</a></p>
<hr style="border:0;border-top:1px solid #E2E8F0;margin:0 0 8px">
${body}
<hr style="border:0;border-top:1px solid #E2E8F0;margin:20px 0 8px">
<p style="font-size:12px;color:#64748B;font-style:italic">${DISCLAIMER}</p>
<p style="font-size:13px;color:#64748B">Questions or trouble with your script? Just reply to this email.</p>
</div>`;

  await sendEmail({
    from: process.env.SCRIPT_EMAIL_FROM || "Next Level Negotiation <scripts@nextlevelnegotiation.com>",
    to: [to],
    replyTo: CONTACT_EMAIL,
    subject: title,
    html,
    text: `Here's a copy of ${inSentence}.\n\nReopen it any time, on any device: ${scriptUrl}\n\n${script}\n\n${DISCLAIMER}`,
  });
}
