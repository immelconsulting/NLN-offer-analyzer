import crypto from "crypto";
import { attachEmail, updateSubmission } from "./store.js";
import { sendEmail } from "./email.js";
import { CONTACT_EMAIL, STRATEGY_SESSION_URL } from "../../src/lib/config.js";

// "Email me my results", offered on the wait screen and the results page.
// Email is optional, so the analysis never depends on it.
//
// The wait screen asks before the analysis has an id, so the browser makes up
// a request reference and sends it with both the analysis and the email.
// Whichever arrives second triggers the send (each side stores its half, then
// checks for the other), so it works even if they close the tab mid-wait. A
// lock stops the rare case of both sides seeing each other from sending twice.

const SITE_URL = new URL(STRATEGY_SESSION_URL).origin;
const HOUR = 60 * 60;
const pendingKey = (ref) => `nln:pending-results:${ref}`;
const refKey = (ref) => `nln:ref:${ref}`;
const sentKey = (id, email) => `nln:results-emailed:${id}:${email}`;

export const isRequestRef = (v) => typeof v === "string" && /^[A-Za-z0-9-]{8,64}$/.test(v);

const money = (n) =>
  typeof n === "number" && Number.isFinite(n) ? `$${Math.round(n).toLocaleString("en-US")}` : null;
const range = (r) =>
  r && money(r.low) ? `${money(r.low)} to ${money(r.stretch)}, with a target of ${money(r.target)}` : null;
const escapeHtml = (s) =>
  String(s).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");

// Only what the free results page already shows; the pre-offer strategies stay
// behind the script purchase.
function summaryLines(flow, analysis = {}) {
  if (flow === "offer") {
    const opportunities = (analysis.opportunities || [])
      .slice(0, 3)
      .map((o) => `${o.title}${o.estimatedImpact ? ` (${o.estimatedImpact})` : ""}`);
    return [
      analysis.offerScore != null &&
        `Your offer score: ${analysis.offerScore}/100${analysis.scoreInterpretation ? `. ${analysis.scoreInterpretation}` : ""}`,
      opportunities.length && `Biggest opportunities: ${opportunities.join("; ")}`,
      analysis.recommendedNextStep && `Recommended next step: ${analysis.recommendedNextStep}`,
    ].filter(Boolean);
  }
  const mr = analysis.market_range;
  return [
    mr
      ? `Your target base salary: ${range(mr.base)}`
      : "We couldn't find reliable market data for this role, so your results explain what to do instead of guessing at a number.",
    mr?.total_comp && `Total compensation: ${range(mr.total_comp)}`,
    flow === "offer_soon" && analysis.offer_benchmark_note && `How to read the offer: ${analysis.offer_benchmark_note}`,
    flow === "offer_soon" && "On the offer call itself, don't accept and don't counter. That call is for gathering information.",
    analysis.biggest_risk && `Your biggest risk: ${analysis.biggest_risk}`,
  ].filter(Boolean);
}

export async function sendResultsEmail({ to, flow, analysis, link }) {
  const lines = summaryLines(flow, analysis);
  const disclaimer =
    "Your results were generated by AI, guided by NLN's negotiation methodology, using market data researched at the time of your request. They're general guidance, not personalized legal, financial, or professional advice.";
  const html = `<div style="font-family:Arial,Helvetica,sans-serif;font-size:15px;line-height:1.5;color:#334155;max-width:640px">
<p style="margin:0 0 14px">Here are your Job Offer Analyzer results, so your numbers are ready before your call.</p>
${lines.map((l) => `<p style="margin:0 0 12px">${escapeHtml(l)}</p>`).join("\n")}
<p style="margin:20px 0"><a href="${link}" style="color:#0099CC;font-weight:bold">See your full results</a></p>
<p style="font-size:12px;color:#64748B;font-style:italic">${disclaimer}</p>
<p style="font-size:13px;color:#64748B">Questions? Just reply to this email.</p>
</div>`;
  await sendEmail({
    from: process.env.SCRIPT_EMAIL_FROM || "Next Level Negotiation <scripts@nextlevelnegotiation.com>",
    to: [to],
    replyTo: CONTACT_EMAIL,
    subject: "Your Job Offer Analyzer results",
    html,
    text: `Here are your Job Offer Analyzer results.\n\n${lines.join("\n\n")}\n\nSee your full results: ${link}\n\n${disclaimer}`,
  });
}

// Attaches the email to the analysis and sends the results, once per address.
export async function deliverResults(redis, id, email) {
  const clean = email.trim().toLowerCase();
  const record = await attachEmail(redis, id, clean);
  if (!record) return false;
  const lock = sentKey(id, clean);
  if (!(await redis.set(lock, 1, { nx: true, ex: 24 * HOUR }))) return true;
  try {
    const token = record.resultsToken || crypto.randomBytes(16).toString("hex");
    if (!record.resultsToken) await updateSubmission(redis, id, { resultsToken: token });
    await sendResultsEmail({
      to: clean,
      flow: record.flow || "offer",
      analysis: record.analysis,
      link: `${SITE_URL}/r/${id}?t=${token}`,
    });
    return true;
  } catch (err) {
    await redis.del(lock); // let a retry try again
    throw err;
  }
}

// The analysis half: called right after a submission is saved.
export async function afterAnalysisSaved(redis, requestRef, id) {
  if (!isRequestRef(requestRef)) return;
  await redis.set(refKey(requestRef), id, { ex: HOUR });
  const pending = await redis.get(pendingKey(requestRef));
  if (pending) await deliverResults(redis, id, String(pending));
}

// The email half: called when someone asks during the wait.
export async function requestResultsByRef(redis, requestRef, email) {
  await redis.set(pendingKey(requestRef), email.trim().toLowerCase(), { ex: HOUR });
  const id = await redis.get(refKey(requestRef));
  if (id) await deliverResults(redis, String(id), email);
}
