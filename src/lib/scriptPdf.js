import { marked } from "marked";

// Turns a generated script (markdown) into a pdfmake document, so "Download
// PDF" produces a real file instead of sending people through the browser's
// print dialog. Handles what the script prompts actually produce: headings,
// paragraphs, bold/italic, lists, the comp table, blockquotes and rules.
//
// pdfmake's bundled font (Roboto) has no emoji, so the 🗣️ "say this" marker
// becomes a bold "Say:" and any other emoji is dropped rather than printing
// as an empty box.

const NAVY = "#001E34";
const NAVY_MID = "#0099CC";
const SLATE = "#334155";
const RULE = "#CBD5E1";

const DISCLAIMER =
  "This script was generated by AI based on NLN's methodology and the details you provided. " +
  "It's meant as general guidance, not personalized legal, financial, or professional advice, " +
  "and outcomes aren't guaranteed.";

function cleanEmoji(text) {
  return text
    .replace(/🗣️?\s*/gu, "\u0000SAY\u0000")
    .replace(/\p{Extended_Pictographic}️?\s*/gu, "")
    .replace(/️/g, "");
}

// Inline tokens → pdfmake text runs.
function inline(tokens = [], style = {}) {
  const runs = [];
  for (const t of tokens) {
    switch (t.type) {
      case "strong":
        runs.push(...inline(t.tokens, { ...style, bold: true }));
        break;
      case "em":
        runs.push(...inline(t.tokens, { ...style, italics: true }));
        break;
      case "del":
        runs.push(...inline(t.tokens, { ...style, decoration: "lineThrough" }));
        break;
      case "link":
        runs.push(
          ...inline(t.tokens, { ...style, link: t.href, color: NAVY_MID, decoration: "underline" })
        );
        break;
      case "br":
        runs.push({ text: "\n", ...style });
        break;
      case "codespan":
        runs.push({ text: decode(t.text), ...style });
        break;
      case "text":
        if (t.tokens) runs.push(...inline(t.tokens, style));
        else runs.push(...textRuns(t.text, style));
        break;
      default:
        runs.push(...textRuns(t.raw || t.text || "", style));
    }
  }
  return runs;
}

function decode(s) {
  return s
    .replace(/&amp;/g, "&")
    .replace(/&lt;/g, "<")
    .replace(/&gt;/g, ">")
    .replace(/&quot;/g, '"')
    .replace(/&#39;/g, "'");
}

function textRuns(raw, style) {
  return cleanEmoji(decode(raw))
    .split("\u0000")
    .filter((part) => part !== "")
    .map((part) =>
      part === "SAY"
        ? { text: "Say: ", ...style, bold: true, color: NAVY_MID }
        : { text: part, ...style }
    );
}

// Block tokens → pdfmake content nodes.
function blocks(tokens = []) {
  const out = [];
  for (const t of tokens) {
    switch (t.type) {
      case "heading":
        out.push({ text: inline(t.tokens), style: `h${Math.min(t.depth, 3)}` });
        break;
      case "paragraph":
        out.push({ text: inline(t.tokens), style: "p" });
        break;
      case "text":
        out.push({ text: inline(t.tokens || [{ type: "text", text: t.text }]), style: "p" });
        break;
      case "list": {
        const items = t.items.map((item) => {
          const content = blocks(item.tokens);
          // Tight list items come back as bare text nodes; drop their
          // paragraph spacing so bullets stay compact.
          return content.length === 1 ? { ...content[0], margin: [0, 0, 0, 3] } : content;
        });
        out.push(
          t.ordered
            ? { ol: items, margin: [0, 0, 0, 8], color: SLATE }
            : { ul: items, margin: [0, 0, 0, 8], color: SLATE }
        );
        break;
      }
      case "table": {
        const header = t.header.map((cell) => ({
          text: inline(cell.tokens),
          bold: true,
          color: NAVY,
          fillColor: "#D8F0F8",
        }));
        const rows = t.rows.map((row) => row.map((cell) => ({ text: inline(cell.tokens) })));
        out.push({
          table: { headerRows: 1, widths: header.map(() => "*"), body: [header, ...rows] },
          layout: {
            hLineColor: () => RULE,
            vLineColor: () => RULE,
            paddingLeft: () => 6,
            paddingRight: () => 6,
            paddingTop: () => 4,
            paddingBottom: () => 4,
          },
          fontSize: 9.5,
          margin: [0, 2, 0, 10],
        });
        break;
      }
      case "blockquote":
        out.push({
          table: { widths: [3, "*"], body: [[{ text: "", fillColor: "#6BCCF7" }, { stack: blocks(t.tokens), italics: true }]] },
          layout: "noBorders",
          margin: [0, 0, 0, 8],
        });
        break;
      case "hr":
        out.push({
          canvas: [{ type: "line", x1: 0, y1: 0, x2: 515, y2: 0, lineWidth: 0.75, lineColor: RULE }],
          margin: [0, 6, 0, 10],
        });
        break;
      case "code":
        out.push({ text: t.text, style: "p" });
        break;
      case "space":
      case "html":
      default:
        break;
    }
  }
  return out;
}

export function scriptPdfFilename(title) {
  return `${title.replace(/[^A-Za-z0-9]+/g, "-").replace(/^-|-$/g, "")}.pdf`;
}

export function buildScriptPdf({ script, title, subtitle }) {
  // Scripts usually open with their own "# ..." heading; use it as the PDF
  // title rather than printing two titles back to back.
  const tokens = marked.lexer(script);
  const firstBlock = tokens.findIndex((t) => t.type !== "space");
  let titleRuns = title;
  if (tokens[firstBlock]?.type === "heading" && tokens[firstBlock].depth === 1) {
    titleRuns = inline(tokens[firstBlock].tokens);
    tokens.splice(firstBlock, 1);
  }

  return {
    pageSize: "LETTER",
    pageMargins: [48, 54, 48, 54],
    info: { title, author: "Next Level Negotiation" },
    content: [
      { text: titleRuns, style: "title" },
      ...(subtitle ? [{ text: subtitle, style: "subtitle" }] : []),
      {
        canvas: [{ type: "line", x1: 0, y1: 0, x2: 515, y2: 0, lineWidth: 1.5, lineColor: NAVY_MID }],
        margin: [0, 4, 0, 14],
      },
      ...blocks(tokens),
      { text: DISCLAIMER, style: "disclaimer" },
    ],
    footer: (page, pages) => ({
      columns: [
        { text: "Next Level Negotiation · jobofferanalyzer.com", alignment: "left" },
        { text: `${page} of ${pages}`, alignment: "right" },
      ],
      margin: [48, 18, 48, 0],
      fontSize: 8,
      color: "#64748B",
    }),
    defaultStyle: { fontSize: 10.5, lineHeight: 1.25, color: SLATE },
    styles: {
      title: { fontSize: 20, bold: true, color: NAVY },
      subtitle: { fontSize: 11, color: "#64748B", margin: [0, 3, 0, 0] },
      h1: { fontSize: 16, bold: true, color: NAVY, margin: [0, 12, 0, 6] },
      h2: { fontSize: 14, bold: true, color: NAVY, margin: [0, 12, 0, 5] },
      h3: { fontSize: 12, bold: true, color: NAVY, margin: [0, 9, 0, 4] },
      p: { margin: [0, 0, 0, 7] },
      disclaimer: { fontSize: 8.5, italics: true, color: "#64748B", margin: [0, 18, 0, 0] },
    },
  };
}
